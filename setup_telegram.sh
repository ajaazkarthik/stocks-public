#!/usr/bin/env bash
# ============================================================
#  Stocks Trading Bot — One-Time Setup Script (macOS/Linux)
#  Run this once, then use start_telegram_bot.sh daily.
# ============================================================
#
# What this script does:
#  1. Verifies python-telegram-bot is installed
#  2. Sets TELEGRAM_BOT_TOKEN (already provided)
#  3. Starts the bot in "ID discovery" mode — open to all users
#  4. Tells you how to find your Telegram user ID
#  5. Prompts you to enter your ID, then saves it to telegram_env.sh
#
# ============================================================

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$SCRIPT_DIR"

TOKEN="8741115130:AAGQhi6LYaArwoPs-3i0XPsC8iRMr3jzoWs"
BOT_USERNAME="Ajaaz_bot"
KNOWN_USER_ID="5986275415"

# Activate venv
if [[ -f ".venv/bin/activate" ]]; then
    source ".venv/bin/activate"
    PIP=".venv/bin/pip"
    PYTHON=".venv/bin/python"
else
    PIP="pip3"
    PYTHON="python3"
fi

echo ""
echo "============================================================"
echo "  Stocks Trading Bot — Setup"
echo "============================================================"
echo ""

# ── Step 1: Check python-telegram-bot ──────────────────────
echo "[1/4] Checking python-telegram-bot..."
if "$PIP" show python-telegram-bot &>/dev/null; then
    VER=$("$PIP" show python-telegram-bot | grep "^Version:" | head -1)
    echo "  $VER — OK"
else
    echo "  Installing python-telegram-bot..."
    "$PIP" install "python-telegram-bot>=20.0" -q
    echo "  Installed OK."
fi

# ── Step 2: Verify token is live ───────────────────────────
echo ""
echo "[2/4] Verifying bot token..."
if curl -sf "https://api.telegram.org/bot${TOKEN}/getMe" -o /dev/null; then
    echo "  Token: VALID"
    echo "  Bot: @$BOT_USERNAME"
else
    echo "  ERROR: Token is invalid or Telegram is unreachable." >&2
    echo "  Check your internet connection and try again." >&2
    exit 1
fi

# ── Step 3: Find the user's Telegram ID ────────────────────
echo ""
echo "[3/4] Finding your Telegram user ID"
echo ""
echo "  ╔═══════════════════════════════════════════════════════╗"
echo "  ║  ACTION REQUIRED — Do this on your PHONE:             ║"
echo "  ║                                                        ║"
echo "  ║  1. Open Telegram                                      ║"
echo "  ║  2. Search: @$BOT_USERNAME                             ║"
echo "  ║  3. Tap START                                          ║"
echo "  ║  4. Send: /id                                          ║"
echo "  ║  5. The bot will reply with a number like: 1234567890  ║"
echo "  ║  6. Copy that number and paste it below                ║"
echo "  ╚═══════════════════════════════════════════════════════╝"
echo ""
echo "  NOTE: The bot must be running for /id to work."
echo "  Starting bot in ID-discovery mode (open to all users)..."
echo ""

# Start bot in background for ID discovery
export TELEGRAM_BOT_TOKEN="$TOKEN"
"$PYTHON" "$SCRIPT_DIR/telegram_bot.py" &
BOT_PID=$!
echo "  Bot started (PID: $BOT_PID)"
echo "  → Now go to Telegram, find @$BOT_USERNAME, send /id"
echo ""

read -rp "  Paste your Telegram user ID here: " USER_ID
USER_ID="${USER_ID// /}"

# Kill discovery bot
kill "$BOT_PID" 2>/dev/null || true
wait "$BOT_PID" 2>/dev/null || true
echo "  Bot stopped."

# Validate it's a number
if ! [[ "$USER_ID" =~ ^[0-9]+$ ]]; then
    echo ""
    echo "  ERROR: '$USER_ID' is not a valid Telegram user ID (must be all digits)." >&2
    exit 1
fi

echo ""
echo "  Your Telegram ID: $USER_ID"

# ── Step 4: Save environment variables ─────────────────────
echo ""
echo "[4/4] Saving configuration..."

GENERATED_DATE="$(date '+%Y-%m-%d %H:%M')"
cat > "$SCRIPT_DIR/telegram_env.sh" <<EOF
#!/usr/bin/env bash
# Stocks Trading Bot — Environment Variables
# Generated by setup_telegram.sh on $GENERATED_DATE
# Source this file before running the bot:
#   source ./telegram_env.sh

export TELEGRAM_BOT_TOKEN="$TOKEN"
export TELEGRAM_ALLOWED_USERS="$USER_ID"
EOF

chmod +x "$SCRIPT_DIR/telegram_env.sh"
echo "  Saved to: telegram_env.sh"
echo ""
echo "  Setup complete! Run ./start_telegram_bot.sh to start the bot."

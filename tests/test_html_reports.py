class TestRegressionPreventionZerodhaSingleton:
    """R7: All Zerodha auth must route through zerodha_auth.get_kite() singleton.

    Creating a second KiteConnect session silently invalidates the first token —
    causing intermittent 'Token expired' errors mid-session. Every script must
    delegate to the zerodha_auth SSOT.
    """

    _ROGUE_PATTERNS = [
        r"KiteConnect\s*\(",
        r"kite\.set_access_token\s*\(",
    ]

    _ALLOWED_FILES = [
        "india-brokers/zerodha_auth.py",     # SSOT — the one place that may create KiteConnect
        "india-brokers/zerodha_login.py",    # Login helper — also allowed
        "india-brokers/test_zerodha_auth.py",# Unit test mocks
    ]

    def _check_file(self, rel_path: str) -> list[str]:
        """Return list of offending lines (rogue KiteConnect usage)."""
        p = ROOT / rel_path
        if not p.exists():
            return []
        violations = []
        text = p.read_text(encoding="utf-8", errors="replace")
        for pattern in self._ROGUE_PATTERNS:
            for m in re.finditer(pattern, text):
                line_no = text[:m.start()].count("\n") + 1
                violations.append(f"  {rel_path}:{line_no}: {m.group().strip()}")
        return violations

    def test_buy_advisor_no_rogue_kiteconnect(self):
        """buy_advisor.py must use get_kite() not raw KiteConnect."""
        violations = self._check_file("tradingview/buy_advisor.py")
        assert not violations, (
            "REGRESSION R7: rogue KiteConnect usage in buy_advisor.py\n"
            + "\n".join(violations)
        )

    def test_platform_watchdog_no_rogue_kiteconnect(self):
        """platform_watchdog.py must use get_kite() not raw KiteConnect."""
        violations = self._check_file("tradingview/platform_watchdog.py")
        assert not violations, (
            "REGRESSION R7: rogue KiteConnect usage in platform_watchdog.py\n"
            + "\n".join(violations)
        )

    def test_platform_watchdog_check_zerodha_no_profile_call(self):
        """_check_zerodha() must NOT call kite.profile() — that is a live Zerodha API call.

        Calling kite.profile() on every watchdog tick (every 90 s, plus twice at
        startup when init-thread + loop-thread both ran check_all() simultaneously)
        caused 5+ Zerodha API calls within 10 seconds — the R7b regression.
        The watchdog must check token validity via is_token_valid() cache read only.
        """
        import re as _re
        src = (ROOT / "tradingview" / "platform_watchdog.py").read_text(
            encoding="utf-8", errors="replace"
        )
        # Find _check_zerodha function body
        fn_match = _re.search(
            r"def _check_zerodha\(\).*?(?=\ndef |\Z)", src, _re.DOTALL
        )
        assert fn_match, "_check_zerodha() not found in platform_watchdog.py"
        fn_body = fn_match.group()
        # Strip string literals and comments before checking — the docstring
        # mentions kite.profile() to explain WHY it must not be called.
        code_only = _re.sub(r'""".*?"""', "", fn_body, flags=_re.DOTALL)
        code_only = _re.sub(r"'''.*?'''", "", code_only, flags=_re.DOTALL)
        code_only = _re.sub(r"#[^\n]*", "", code_only)
        assert "kite.profile()" not in code_only, (
            "REGRESSION R7b: _check_zerodha() must NOT call kite.profile().\n"
            "kite.profile() is a live Zerodha API call that fires on every "
            "watchdog tick, causing multiple unexpected auth events at startup. "
            "Use is_token_valid() (cache read) for health checks instead."
        )

    def test_global_dashboard_no_rogue_kiteconnect(self):
        """global_portfolio_dashboard.py must use get_kite() not raw KiteConnect."""
        violations = self._check_file("global_portfolio_dashboard.py")
        assert not violations, (
            "REGRESSION R7: rogue KiteConnect usage in global_portfolio_dashboard.py\n"
            + "\n".join(violations)
        )



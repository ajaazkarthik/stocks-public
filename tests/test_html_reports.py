    def test_broker_pnl_chart_applies_fx_conversion(self):
        """Bug 2026-04-22: JPY/HKD positions must be converted to AUD before chart aggregation.

        Without FX conversion, ¥10,000 (≈ A$99) was equal in magnitude
        to A$10,000 on the bar chart, inflating foreign-currency broker bars.
        """
        from collections import defaultdict
        # Positions spanning 3 currencies: AUD, JPY, HKD
        positions = [
            {"broker": "Moomoo-AU", "currency": "AUD", "pnl": 100.0},
            {"broker": "AngelOne",  "currency": "JPY", "pnl": 10_000.0},  # ≈ A$99
            {"broker": "Moomoo-SG", "currency": "HKD", "pnl": 1_000.0},  # ≈ A$197
        ]
        _FX_TO_AUD = {
            "AUD": 1.0, "USD": 1.54, "HKD": 0.197, "SGD": 1.14,
            "INR": 0.0185, "JPY": 0.0099, "GBP": 1.95, "CAD": 1.14, "KRW": 0.0011,
        }
        broker_pnl: dict[str, float] = defaultdict(float)
        for p in positions:
            ccy = str(p.get("currency", "USD")).upper()
            fx  = _FX_TO_AUD.get(ccy, 1.0)
            broker_pnl[p["broker"]] += float(p.get("pnl", 0) or 0) * fx

        # AUD stays 100.0
        assert abs(broker_pnl["Moomoo-AU"] - 100.0) < 0.01
        # JPY 10,000 × 0.0099 ≈ 99.0 — NOT 10,000
        assert abs(broker_pnl["AngelOne"] - 99.0) < 1.0
        assert broker_pnl["AngelOne"] < 200.0, "JPY pnl must be FX-converted, not raw"
        # HKD 1,000 × 0.197 = 197.0 — NOT 1,000
        assert abs(broker_pnl["Moomoo-SG"] - 197.0) < 1.0
        assert broker_pnl["Moomoo-SG"] < 500.0, "HKD pnl must be FX-converted, not raw"


def _run_post_alert_summary(monkeypatch, notes, *, summary_len):
    """Drive _post_alert_summary with a stubbed summary and a fake bot."""
    import asyncio
    import report_scheduler as rs
    from tradingview.scheduler import formatting, stock_results

    summary = "S" * summary_len
    monkeypatch.setattr(
        rs, "_extract_stock_result",
        lambda *a, **k: stock_results.StockResult(status=stock_results.STATUS_EMPTY),
    )
    monkeypatch.setattr(
        rs, "_extract_options_alerts",
        lambda *a, **k: {"options": [], "status": "success", "errors": []},
    )
    monkeypatch.setattr(
        rs, "_format_alert_summary",
        lambda *a, **k: [formatting.MessagePart(html_text=summary, plain_text=summary)],
    )

    sent: list = []

    class _Bot:
        async def send_message(self, **kwargs):
            sent.append(kwargs["text"])

    asyncio.run(rs._post_alert_summary(_Bot(), 123, threshold=70, notes=notes))
    return sent


def test_notes_that_fit_are_appended_to_summary(monkeypatch):
    sent = _run_post_alert_summary(monkeypatch, ["step failed: x"], summary_len=100)

    assert len(sent) == 1
    assert sent[0].endswith("step failed: x")


def test_notes_that_overflow_are_sent_separately(monkeypatch):
    """Regression: notes appended after the split pushed the message over 4096."""
    notes = ["F" * 300]
    sent = _run_post_alert_summary(monkeypatch, notes, summary_len=3953)

    assert all(len(t) <= 4096 for t in sent), "a message exceeded Telegram's 4096-char cap"
    assert len(sent) == 2
    assert sent[0] == "S" * 3953          # summary stays intact
    assert sent[1].endswith("F" * 300)    # notes delivered separately


def test_oversized_notes_are_chunked(monkeypatch):
    notes = ["N" * 9000]
    sent = _run_post_alert_summary(monkeypatch, notes, summary_len=100)

    assert all(len(t) <= 4096 for t in sent)
    assert len(sent) > 1
    # The note content is preserved verbatim; only a short label is prefixed.
    joined = "".join(sent[1:])
    assert joined.count("N") == 9000
    assert joined.startswith("⚠️ note: ")


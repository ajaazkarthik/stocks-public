def _load(relative_path: str) -> Optional[BeautifulSoup]:
    """Parse HTML file relative to workspace root. Returns None if file absent."""
    p = ROOT / relative_path
    if not p.exists():
        return None
    try:
        return BeautifulSoup(p.read_text(encoding="utf-8", errors="replace"), "html.parser")
    except Exception:
        return None


def _text(soup: BeautifulSoup) -> str:
    """Visible text content of the page (no JS, no attributes)."""
    return soup.get_text(separator=" ", strip=True)


# Pattern that catches NaN/None/undefined leaking from Python/JS
_BUG_PATTERNS = [
    (re.compile(r"\bNaN\b"),         "NaN visible in output"),
    (re.compile(r"\bnull\b"),        "null visible in output"),
    (re.compile(r"Traceback \(most recent call last\)", re.I),
                                     "Python traceback in HTML"),
    (re.compile(r"₹\s*nan", re.I),   "₹NaN price value"),
    (re.compile(r"\$\s*nan", re.I),  "$NaN price value"),
    (re.compile(r"undefined", re.I), "'undefined' visible in output"),
    (re.compile(r"NameError|AttributeError|KeyError|TypeError",
                re.I),               "Python exception class name in output"),
]

# "None" is tricky — can appear in legitimate text. Check it only in quantity/price contexts.
_NONE_IN_PRICE = re.compile(r"(?:₹|AUD\$?|\$|HKD|SGD)\s*None\b", re.I)


def _check_no_bugs(soup: BeautifulSoup, path: str) -> None:
    """Assert none of the common bug patterns are present in the rendered text."""
    text = _text(soup)
    for pattern, description in _BUG_PATTERNS:
        m = pattern.search(text)
        assert not m, (
            f"[{path}] Bug detected — {description}: "
            f"'…{text[max(0, m.start()-30):m.end()+30]}…'"
        )
    m = _NONE_IN_PRICE.search(text)
    assert not m, (
        f"[{path}] None in price context: "
        f"'…{text[max(0, m.start()-30):m.end()+30]}…'"
    )


# ══════════════════════════════════════════════════════════════════════════════
# Require helper — FAIL (not skip) when the file hasn't been generated yet.
# The _ensure_reports_exist() conftest fixture stubs all paths before tests run.
# ══════════════════════════════════════════════════════════════════════════════

def _require(relative_path: str) -> BeautifulSoup:
    soup = _load(relative_path)
    if soup is None:
        pytest.fail(f"File not found: {relative_path} — was the report not generated and no stub provided?")
    return soup



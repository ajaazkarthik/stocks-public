class TestWSIdleBreak:
    """
    Regression guard: _fetch_ws_fields must NOT wait the full ws_timeout when
    all contract data has already arrived.

    Root cause (2026-05-11): the WS loop broke only on `quote_completed` events,
    which TV WebSocket sends inconsistently for options chains.  Result: every
    symbol waited the full 12 s regardless of how fast the data arrived.
    Fix: break as soon as len(result) >= len(contract_symbols) OR after 2
    consecutive recv-timeouts with no new data (idle-streak detector).
    """

    def test_ws_idle_break_fires_before_full_timeout(self, monkeypatch):
        """
        When asyncio.TimeoutError fires on every recv, idle_streak must trigger
        the early-exit after ~2 cycles (~4 s), NOT after the full 8 s timeout.
        """
        import asyncio, time, sys, os
        sys.path.insert(0, os.path.join(os.path.dirname(__file__), "."))
        import tradingview.options.hybrid_options as ho


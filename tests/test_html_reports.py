"""
Automated Quality Checks for every HTML report generated by the trading system.
================================================================================
These tests catch the bugs you'd otherwise find by manually opening each file:

  • NaN / None / undefined leaking into rendered output
  • Empty reports (generated with zero data)
  • Python tracebacks baked into the HTML
  • Malformed / unparseable HTML
  • Required UI sections missing
  • Score / price values out of valid range
  • Tables with too few rows to be useful
  • Broken card / ticker markup in signal reports

Run all:
    python -m pytest tests/test_html_reports.py -v

Run with HTML report:
    python -m pytest tests/test_html_reports.py -v --html=reports/test_html_quality.html

Run just card-layout checks:
    python -m pytest tests/test_html_reports.py -v -k "card"
"""

